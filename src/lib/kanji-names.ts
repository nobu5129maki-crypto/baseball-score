function toHiragana(input: string): string {
  return input.replace(/[\u30a1-\u30f6]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60));
}

function normalize(input: string): string {
  return toHiragana(input).trim().toLowerCase().replace(/\s+/g, "");
}

export function kanjiCandidates(input: string): string[] {
  const key = normalize(input);
  if (!key) return [];
  return SURNAMES[key] ?? [];
}
